const messages: Record<Locale, Record<MessageKey, string>> = { pt, en, es }

const CAMPAIGN_STATUS_KEY: Record<string, MessageKey> = {
  em_execucao: "status.running",
  aberta: "status.open",
  rascunho: "status.draft",
  concluida: "status.done",
  cancelada: "status.cancelled",
  arquivada: "status.archived",
}

const PARTICIPANT_STATUS_KEY: Record<string, MessageKey> = {
  convidado: "participant.invited",
  candidato: "participant.review",
  selecionado: "participant.selected",
  recusado: "participant.declined",
  entregue: "participant.delivered",
}

export function campaignStatusKey(status: string): MessageKey {
  return CAMPAIGN_STATUS_KEY[status] ?? "status.draft"
}

export function participantStatusKey(status: string): MessageKey {
  return PARTICIPANT_STATUS_KEY[status] ?? "participant.review"
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let text = messages[locale][key] ?? messages.pt[key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function useI18n() {
  const locale = usePreferencesStore((state) => state.locale)
  const t = (key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars)
  return { locale, t }
}
