const PUBLICATION_TYPE: Record<MonitorPost["type"], RelationshipEventType> = {
  reels: "reel",
  post_feed: "post",
  tiktok: "post",
  video_youtube: "video",
  stories: "story",
}

function publicationsAsEvents(): RelationshipEvent[] {
  const organizationByCampaign = new Map(CAMPAIGNS.map((campaign) => [campaign.id, campaign.organizationId]))
  return MONITOR_POSTS.flatMap((post) => {
    const organizationId = organizationByCampaign.get(post.campaignId)
    if (!organizationId) return []
    return [{
      id: `content-${post.id}`,
      creatorId: post.creatorId,
      organizationId,
      type: PUBLICATION_TYPE[post.type],
      description: post.caption,
      campaignId: post.campaignId,
      campaignName: post.campaignName,
      date: post.publishedAt.slice(0, 10),
      network: post.network,
      reach: post.reach,
      engagement: post.engagement,
    }]
  })
}

